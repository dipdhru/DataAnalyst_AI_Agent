"""Unpack BIRD Mini-Dev databases and write config.bird.yaml.

    uv run python scripts/setup_bird.py

Expects (see docs/bird-alignment.md):
    data/bird/download/minidev.zip               databases, from the bird-bench/mini_dev README
    data/bird/questions/mini_dev_sqlite.jsonl    2026 questions, from HF birdsql/bird_mini_dev

Extracts only `<db_id>/<db_id>.sqlite` and `<db_id>/database_description/*.csv` into
data/bird/dev_databases/. The zip is third-party input: no member is run, and paths are checked
so nothing lands outside that folder. Questions come from the jsonl, not from the zip (the zip's
copy is the older 2024 revision).
"""

from __future__ import annotations

import json
import shutil
import sys
import zipfile
from pathlib import Path, PurePosixPath

import yaml

ROOT = Path(__file__).resolve().parents[1]
BIRD = ROOT / "data" / "bird"
ZIP = BIRD / "download" / "minidev.zip"
QUESTIONS = BIRD / "questions" / "mini_dev_sqlite.jsonl"
DB_DIR = BIRD / "dev_databases"
CONFIG = ROOT / "config.bird.yaml"


def wanted(member: PurePosixPath, db_ids: set[str]) -> PurePosixPath | None:
    """Map a zip member to its path under DB_DIR, or None to skip it."""
    parts = member.parts
    for i, part in enumerate(parts):
        if part in db_ids:
            rest = parts[i + 1 :]
            if rest == (f"{part}.sqlite",):
                return PurePosixPath(part, *rest)
            if len(rest) == 2 and rest[0] == "database_description" and rest[1].endswith(".csv"):
                return PurePosixPath(part, *rest)
    return None


def extract(db_ids: set[str]) -> None:
    DB_DIR.mkdir(parents=True, exist_ok=True)
    root = DB_DIR.resolve()
    with zipfile.ZipFile(ZIP) as outer:
        for info in outer.infolist():
            name = PurePosixPath(info.filename)
            if name.suffix == ".zip" and "dev_databases" in name.name:
                # Some releases nest the databases in an inner zip.
                with outer.open(info) as inner_file, zipfile.ZipFile(inner_file) as inner:
                    _extract_members(inner, db_ids, root)
        _extract_members(outer, db_ids, root)


def _extract_members(archive: zipfile.ZipFile, db_ids: set[str], root: Path) -> None:
    for info in archive.infolist():
        if info.is_dir() or "__MACOSX" in info.filename:
            continue
        target = wanted(PurePosixPath(info.filename), db_ids)
        if target is None:
            continue
        dest = (root / target).resolve()
        if not dest.is_relative_to(root):
            raise SystemExit(f"refusing to write outside {root}: {info.filename}")
        if dest.exists() and dest.stat().st_size == info.file_size:
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        with archive.open(info) as src, dest.open("wb") as out:
            shutil.copyfileobj(src, out)


def write_config(db_ids: set[str]) -> None:
    config = {
        "state_dir": "state/bird",
        # Benchmark runs need full results: a capped result would score as wrong.
        "query": {"default_row_limit": 1000, "max_row_limit": 1_000_000, "timeout_seconds": 120},
        "profiling": {"sample_values": 5, "max_rows": 1_000_000, "timeout_seconds": 300},
        "uploads": {"name": "bird_uploads"},
        "sources": [
            {"name": db, "type": "sqlite", "path": f"data/bird/dev_databases/{db}/{db}.sqlite"}
            for db in sorted(db_ids)
        ],
    }
    header = "# Generated by scripts/setup_bird.py: BIRD Mini-Dev databases as sources.\n"
    CONFIG.write_text(header + yaml.safe_dump(config, sort_keys=False))


def main() -> int:
    for path in (ZIP, QUESTIONS):
        if not path.exists():
            print(f"missing {path.relative_to(ROOT)}; see docs/bird-alignment.md")
            return 1
    db_ids = {json.loads(line)["db_id"] for line in QUESTIONS.open()}
    extract(db_ids)
    missing = sorted(db for db in db_ids if not (DB_DIR / db / f"{db}.sqlite").exists())
    if missing:
        print(f"databases not found in the zip: {missing}")
        return 1
    write_config(db_ids)
    print(f"{len(db_ids)} databases in {DB_DIR.relative_to(ROOT)}, config in {CONFIG.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
